"""
@file test_models_integration.py
@brief Integration tests for database models against a real PostgreSQL instance.

Verifies that models can be inserted, queried, and that DB-level features
(FKs, triggers, views, soft-delete) work correctly.
"""

import uuid

import pytest
from sqlalchemy import select, text
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker, create_async_engine

import app.models  # noqa: F401
from app.models.community import Community
from app.models.user import User

TEST_DB_URL = "postgresql+asyncpg://nexara:nexara@localhost:5432/nexara_test"
COMMUNITY_UUID = uuid.UUID("00000000-0000-0000-0000-000000000001")


@pytest.fixture
async def session():
    """@brief Transactional session — rolled back after each test."""
    engine = create_async_engine(TEST_DB_URL, echo=False)
    factory = async_sessionmaker(engine, class_=AsyncSession, expire_on_commit=False)
    async with factory() as sess:
        async with sess.begin():
            yield sess
            await sess.rollback()
    await engine.dispose()


class TestUserCRUD:
    """@brief Verify User model works against PostgreSQL."""

    async def test_insert_and_query_user(self, session: AsyncSession):
        """@brief Insert a user and retrieve by email."""
        user = User(
            community_id=COMMUNITY_UUID,
            email="test@nexara.dev",
            username="testuser",
            display_name="Test User",
            role="member",
        )
        session.add(user)
        await session.flush()

        result = await session.execute(select(User).where(User.email == "test@nexara.dev"))
        fetched = result.scalar_one()
        assert fetched.username == "testuser"
        assert fetched.display_name == "Test User"
        assert fetched.id is not None

    async def test_uuid_generated_by_database(self, session: AsyncSession):
        """@brief The id column should be generated by Postgres, not Python."""
        user = User(
            community_id=COMMUNITY_UUID,
            email="uuid@nexara.dev",
            username="uuiduser",
            display_name="UUID User",
        )
        session.add(user)
        await session.flush()

        assert user.id is not None
        assert isinstance(user.id, uuid.UUID)

    async def test_default_role_is_member(self, session: AsyncSession):
        """@brief Users should default to 'member' role."""
        user = User(
            community_id=COMMUNITY_UUID,
            email="role@nexara.dev",
            username="roleuser",
            display_name="Role User",
        )
        session.add(user)
        await session.flush()

        result = await session.execute(select(User).where(User.username == "roleuser"))
        assert result.scalar_one().role == "member"


class TestSoftDeleteView:
    """@brief Verify the active_users view filters soft-deleted records."""

    async def test_active_users_excludes_deleted(self, session: AsyncSession):
        """@brief A user with deleted_at set should not appear in active_users."""
        user = User(
            community_id=COMMUNITY_UUID,
            email="active@nexara.dev",
            username="activeuser",
            display_name="Active User",
        )
        session.add(user)
        await session.flush()

        result = await session.execute(
            text("SELECT count(*) FROM active_users WHERE email = 'active@nexara.dev'")
        )
        assert result.scalar() == 1

        await session.execute(
            text("UPDATE users SET deleted_at = now() WHERE email = 'active@nexara.dev'")
        )

        result = await session.execute(
            text("SELECT count(*) FROM active_users WHERE email = 'active@nexara.dev'")
        )
        assert result.scalar() == 0


class TestUpdatedAtTrigger:
    """@brief Verify the updated_at trigger fires on UPDATE."""

    async def test_updated_at_changes_on_update(self, session: AsyncSession):
        """@brief updated_at should be refreshed by the trigger on update."""
        user = User(
            community_id=COMMUNITY_UUID,
            email="trigger@nexara.dev",
            username="triggeruser",
            display_name="Trigger User",
        )
        session.add(user)
        await session.flush()

        original_updated = user.updated_at

        await session.execute(
            text(
                "UPDATE users SET display_name = 'Updated Name' WHERE email = 'trigger@nexara.dev'"
            )
        )

        result = await session.execute(
            text("SELECT updated_at FROM users WHERE email = 'trigger@nexara.dev'")
        )
        new_updated = result.scalar()
        assert new_updated >= original_updated


class TestSeedData:
    """@brief Verify seed data was inserted by the migration."""

    async def test_community_exists(self, session: AsyncSession):
        """@brief The default community should be seeded."""
        result = await session.execute(select(Community).where(Community.id == COMMUNITY_UUID))
        community = result.scalar_one()
        assert community.name == "Nexara"

    async def test_branding_exists(self, session: AsyncSession):
        """@brief Default branding row should be seeded."""
        result = await session.execute(
            text("SELECT community_name FROM community_branding WHERE community_id = :cid"),
            {"cid": str(COMMUNITY_UUID)},
        )
        assert result.scalar() == "Nexara"
